function hasLateCheckIn(records, stationNames, hour) {
  return records.some(r =>
    stationNames.some(name => r.stationName.includes(name)) &&
    new Date(r.checkInTime).getHours() >= hour &&
    (r.memo || '').trim().length > 0
  );
}

